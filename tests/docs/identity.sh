#!/usr/bin/env bash
#
# identity.sh - the repository knows its own name.
#
# The project moved from a personal account to an organisation, and the move
# was half-done for a while: the GitHub links were rewritten, but every
# `raw.githubusercontent.com/NggKhaiz/ZMRIG/...` install command still pointed
# at the old owner. `github.com/<owner>/<repo>` 301-redirects after a transfer;
# `raw.githubusercontent.com` does not, so the one command the README opens with
# was a 404 dressed up as an install instruction.
#
# Nothing about that is visible in a diff that looks fine, which is why this
# file exists. It derives the owner and repository from the git remote - the
# only place that cannot drift, because git will not push anywhere else - and
# then checks the places that quote it:
#
#   * package.json's repository field and homepage;
#   * site/docusaurus.config.js (organizationName, projectName, url);
#   * the install command in oneclick.sh, the README, the builder library, the
#     landing page, and the published copies under web/;
#   * that no file outside legacy/ still names the previous owner;
#   * that the author's attribution survived the move.
#
#   bash tests/docs/identity.sh
#
# Exit code 0 when every name agrees, 1 otherwise.

set -uo pipefail

ROOT=$(cd -- "$(dirname -- "${0}")/../.." && pwd)
cd "$ROOT" || exit 2

pass=0
fail=0
skip=0

ok()   { pass=$((pass + 1)); printf ' PASS %s\n' "$1"; }
bad()  { fail=$((fail + 1)); printf ' FAIL %s\n' "$1"; }
skip() { skip=$((skip + 1)); printf ' SKIP %s\n' "$1"; }

# --- where does this repository actually live ---------------------------------

remote=$(git remote get-url origin 2>/dev/null || true)

if [ -z "$remote" ]; then
    skip "no git remote, cannot derive owner/repository"
    printf '\n    %d passed, %d failed, %d skipped\n' "$pass" "$fail" "$skip"
    exit 0
fi

slug=$(printf '%s' "$remote" \
    | sed -e 's|^git@[^:]*:|https://github.com/|' \
          -e 's|^ssh://git@github.com/||' \
          -e 's|^https://github.com/||' \
          -e 's|\.git$||')

OWNER=${slug%%/*}
REPO=${slug#*/}

if [ -z "$OWNER" ] || [ -z "$REPO" ] || [ "$OWNER" = "$REPO" ]; then
    bad "cannot parse owner/repository from remote: $remote"
    printf '\n    %d passed, %d failed, %d skipped\n' "$pass" "$fail" "$skip"
    exit 1
fi

ok "remote names $OWNER/$REPO"

# --- files that must agree ----------------------------------------------------

# The published site is generated, but it is committed here, so it is part of
# what ships. `legacy/` is a frozen archive: its URLs point at where the code
# lived in 2023 and rewriting them would falsify it.
tracked() {
    git ls-files \
        | grep -v '^legacy/' \
        | grep -v '^site/node_modules/' \
        | grep -v '^site/build/' \
        | grep -v '^site/\.docusaurus/' \
        | grep -v '^node_modules/'
}

# Sources: everything a human edits. The published trees are generated by
# `scripts/publish-site.sh` and are checked separately, below.
sources() {
    tracked | grep -vE '^(web|assets|docs|vi|search-index\.json|index\.html|404\.html|sitemap\.xml|robots\.txt)' \
        | grep -vE '/assets/|/search-index\.json$|/index\.html$|/404\.html$' \
        | grep -vxF 'tests/docs/identity.sh'
}

wanted="https://raw.githubusercontent.com/$OWNER/$REPO/BETA/oneclick.sh"

for f in oneclick.sh README.md site/src/lib/command.mjs site/src/pages/index.jsx \
         site/docs/install/quickstart.md site/docs/pools/coins.mdx \
         doc/INSTALL.md; do
    [ -f "$f" ] || { bad "$f is missing"; continue; }
    if grep -qF -- "$wanted" "$f"; then
        ok "$f installs from $OWNER/$REPO"
    else
        bad "$f does not carry $wanted"
    fi
done

# --- one install URL in the sources, and one in the published copy ------------

# site/src/lib/command.mjs and site/src/pages/index.jsx both hold the URL
# because one is the builder's pure library and the other is a React page; a
# shared import would make the page depend on the library's module graph for a
# single string. Two copies is a deliberate trade: this check is the price.
urls=$(sources | grep -E '\.(md|mdx|js|jsx|mjs|sh|yml|yaml)$|^README' \
       | xargs grep -hoE 'https://raw\.githubusercontent\.com/[A-Za-z0-9._-]+/[A-Za-z0-9._-]+/BETA/oneclick\.sh' 2>/dev/null \
       | sort -u)

count=$(printf '%s\n' "$urls" | grep -c . || true)
if [ "$count" -eq 1 ] && [ "$urls" = "$wanted" ]; then
    ok "every install command in the sources is the same URL"
else
    bad "the sources quote $count distinct install URL(s):"
    printf '%s\n' "$urls" | sed 's/^/        /'
fi

# The committed site is what a visitor downloads; regenerating it is a separate
# step that is easy to forget, so it is checked here rather than assumed.
published() {
    tracked | grep -E '^(web/|assets/|docs/|vi/|index\.html|404\.html|search-index\.json|sitemap\.xml|robots\.txt)'
}

for f in web/index.html index.html vi/index.html; do
    [ -f "$f" ] || continue
    if grep -qF -- "raw.githubusercontent.com/$OWNER/$REPO/" "$f"; then
        ok "published $f points at $OWNER/$REPO"
    else
        bad "published $f still carries an old install URL (rebuild + publish the site)"
    fi
done

# --- nobody still names the previous owner -----------------------------------

# Kept as literals on purpose: a variable would have to be updated by the move
# it is meant to detect.
stale="NggKhaiz/ZMRIG
nggkhaiz.github.io"

for needle in $stale; do
    for scope in sources published; do
        hits=$($scope | xargs grep -lF -- "$needle" 2>/dev/null || true)
        if [ -z "$hits" ]; then
            ok "no $scope file outside legacy/ mentions $needle"
        else
            bad "$scope files still mention $needle:"
            n=$(printf '%s\n' "$hits" | grep -c . || true)
            printf '%s\n' "$hits" | head -6 | sed 's/^/        /'
            [ "$n" -gt 6 ] && printf '        ... and %d more\n' "$((n - 6))"
        fi
    done
done

# --- raw.githubusercontent.com, which does not redirect ----------------------
#
# GitHub redirects github.com/<old>/<repo> to the new owner after a transfer, so
# a stale link there costs a round trip and nothing else. raw.githubusercontent.com
# serves straight from a keyed store and 404s. That asymmetry is why this check
# covers the whole repository, legacy archive included: an archived page is
# allowed to say where the code lived in 2023, but it is not allowed to hand
# somebody a command that cannot download anything.

# Every match must carry owner *and* repository: a lone owner is what a search
# index keeps after it splits a URL at the hyphen, not a link somebody can click.
pairs=$(git ls-files | grep -vxF 'tests/docs/identity.sh' \
    | xargs grep -hoIE 'raw\.githubusercontent\.com/[A-Za-z0-9._-]+/[A-Za-z0-9._-]+' 2>/dev/null \
    | sed 's|raw\.githubusercontent\.com/||' | sort -u)

foreign=$(printf '%s\n' "$pairs" | grep -vxF -- "$OWNER/$REPO" | grep . || true)

if [ -z "$foreign" ]; then
    ok "every raw.githubusercontent.com link belongs to $OWNER/$REPO"
else
    bad "raw.githubusercontent.com links point somewhere else:"
    printf '%s\n' "$foreign" | sed 's/^/        /'
fi

# --- package metadata ---------------------------------------------------------

if grep -qF -- "$OWNER/$REPO" package.json; then
    ok "package.json repository names $OWNER/$REPO"
else
    bad "package.json repository does not name $OWNER/$REPO"
fi

if grep -qF -- "https://$(printf '%s' "$OWNER" | tr '[:upper:]' '[:lower:]').github.io/$REPO" package.json; then
    ok "package.json homepage matches the Pages host"
else
    bad "package.json homepage does not match https://$(printf '%s' "$OWNER" | tr '[:upper:]' '[:lower:]').github.io/$REPO"
fi

# --- docusaurus --------------------------------------------------------------

cfg=site/docusaurus.config.js
if [ -f "$cfg" ]; then
    for pair in "organizationName:$OWNER" "projectName:$REPO"; do
        key=${pair%%:*}
        want=${pair#*:}
        if grep -qE "$key:[[:space:]]*\"$want\"" "$cfg"; then
            ok "$cfg $key is $want"
        else
            bad "$cfg $key is not $want"
        fi
    done

    host="https://$(printf '%s' "$OWNER" | tr '[:upper:]' '[:lower:]').github.io"
    if grep -qF "const SITE = \"$host\";" "$cfg"; then
        ok "$cfg serves from $host"
    else
        bad "$cfg does not declare const SITE = \"$host\";"
    fi

    if grep -qF "const REPO = \"https://github.com/$OWNER/$REPO\";" "$cfg"; then
        ok "$cfg links to $OWNER/$REPO"
    else
        bad "$cfg does not declare const REPO = \"https://github.com/$OWNER/$REPO\";"
    fi
else
    bad "$cfg is missing"
fi

# --- the author is still the author ------------------------------------------

# A repository move is not a change of who wrote the code. The organisation owns
# the URL; @nggkhaiz still owns the work, and that has to stay visible.
for f in README.md NOTICE; do
    if grep -qF -- "nggkhaiz" "$f"; then
        ok "$f still credits @nggkhaiz"
    else
        bad "$f lost the @nggkhaiz attribution"
    fi
done

printf '\n    %d passed, %d failed, %d skipped\n' "$pass" "$fail" "$skip"
[ "$fail" -eq 0 ]
