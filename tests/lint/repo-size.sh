#!/usr/bin/env bash
# A repository that is downloaded by every rig should not carry build junk.
#
# This file exists because one did: a 3.6 MB shellcheck wheel sat in the root of
# the repository for months. Nothing referenced it, no test noticed, and every
# clone and every `docker build` carried it. The list below is the files that
# are *supposed* to be big (the RandomX C sources are the engine), so anything
# else over the limit is a mistake rather than a decision.
#
#   bash tests/lint/repo-size.sh            check
#   bash tests/lint/repo-size.sh --list     show the ten largest files
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT" || exit 1

LIMIT_KB=${LIMIT_KB:-1024}
fail=0

# Large by design: the engine's C/C++ sources are the program, and the search
# index is generated by the docs build (Docusaurus, one JSON per locale, and it
# is committed twice on purpose - `web/` for the Actions deploy and the root for
# the branch deploy; identical blobs, so Git stores them once).
is_expected() {
    case "$1" in
        src/*|zmrig/capi/*) return 0 ;;
        web/*) return 0 ;;
        assets/*|docs/*|vi/*|img/*|search-index.json) return 0 ;;
        *) return 1 ;;
    esac
}

while IFS= read -r line; do
    size_kb=${line%%$'\t'*}
    file=${line#*$'\t'}
    [ "${size_kb:-0}" -le "$LIMIT_KB" ] && continue
    is_expected "$file" && continue
    echo "  too large: ${file} (${size_kb} KB, limit ${LIMIT_KB} KB)"
    fail=1
done < <(git ls-files -z | xargs -0 -r du -k 2>/dev/null | sort -rn | head -40)

if [ "${1:-}" = "--list" ]; then
    echo "largest tracked files:"
    git ls-files -z | xargs -0 -r du -k 2>/dev/null | sort -rn | head -10 | awk -F'\t' '{printf "  %6s KB  %s\n", $1, $2}'
fi

if [ "$fail" = 1 ]; then
    echo "  the download size is a feature: see .gitignore and tests/lint/repo-size.sh"
    exit 1
fi

echo "repo size ok: nothing over ${LIMIT_KB} KB outside src/"
